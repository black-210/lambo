/// Write the pentest report as pretty‑printed JSON.
pub fn write_json_report(report: &PentestReport, out_path: &str) -> Result<()> {
    let json = serde_json::to_string_pretty(report)?;
    fs::write(out_path, json)?;
    Ok(())
}

/// Render an HTML report from a `PentestReport`.
pub fn render_html_report(report: &PentestReport) -> String {
    let mut rows = String::new();
    for r in &report.results {
        let status_color = if r.success { "#2ecc71" } else { "#e74c3c" };
        let status_text  = if r.success { "SUCCESS" } else { "FAIL" };
        let vulns = r.matched_vulns.join(", ");
        rows.push_str(&format!(
            r#"<tr>
                <td>{name}</td>
                <td style="color:{color};font-weight:bold">{status}</td>
                <td>{conf:.0}%</td>
                <td>{elapsed} ms</td>
                <td><code>{vulns}</code></td>
                <td><pre style="max-width:400px;overflow:auto">{details}</pre></td>
            </tr>"#,
            name    = r.attack_name,
            color   = status_color,
            status  = status_text,
            conf    = r.confidence * 100.0,
            elapsed = r.elapsed_ms,
            vulns   = vulns,
            details = serde_json::to_string_pretty(&r.details).unwrap_or_default(),
        ));
    }

    let recs_html: String = report.recommendations.iter()
        .map(|r| format!("<li>{}</li>", r))
        .collect::<Vec<_>>()
        .join("\n");

    let risk_color = if report.risk_score >= 70.0 { "#e74c3c" }
        else if report.risk_score >= 40.0 { "#f39c12" }
        else { "#2ecc71" };

    format!(r#"<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8"/>
<title>Red‑Team Hardware Pentest Report – {target}</title>
<style>
  body {{ font-family: 'Segoe UI', Arial, sans-serif; background:#0d1117; color:#c9d1d9; margin:0; padding:20px; }}
  h1 {{ color:#58a6ff; border-bottom:2px solid #30363d; padding-bottom:10px; }}
  h2 {{ color:#79c0ff; }}
  .summary-box {{ display:flex; gap:20px; flex-wrap:wrap; margin:20px 0; }}
  .metric {{ background:#161b22; border:1px solid #30363d; border-radius:8px; padding:16px 24px; text-align:center; min-width:140px; }}
  .metric .value {{ font-size:2em; font-weight:bold; }}
  .metric .label {{ font-size:0.85em; color:#8b949e; }}
  table {{ width:100%; border-collapse:collapse; margin:20px 0; }}
  th {{ background:#161b22; color:#58a6ff; padding:10px; border:1px solid #30363d; text-align:left; }}
  td {{ padding:8px 10px; border:1px solid #30363d; vertical-align:top; }}
  tr:nth-child(even) {{ background:#0d1117; }}
  tr:nth-child(odd) {{ background:#161b22; }}
  pre {{ font-family:monospace; font-size:0.78em; background:#010409; padding:8px; border-radius:4px; white-space:pre-wrap; }}
  code {{ background:#010409; padding:2px 6px; border-radius:4px; font-family:monospace; }}
  .rec-list {{ background:#161b22; border:1px solid #30363d; border-radius:8px; padding:16px 24px; }}
  .rec-list li {{ margin:6px 0; }}
  .risk-badge {{ display:inline-block; padding:6px 18px; border-radius:20px; font-weight:bold; font-size:1.1em; color:#fff; background:{risk_color}; }}
</style>
</head>
<body>
<h1>🔴 Red‑Team Hardware Security Pentest Report</h1>

<div class="summary-box">
  <div class="metric"><div class="value" style="color:#58a6ff">{target}</div><div class="label">Target</div></div>
  <div class="metric"><div class="value">{total}</div><div class="label">Total Attacks</div></div>
  <div class="metric"><div class="value" style="color:#2ecc71">{succeeded}</div><div class="label">Succeeded</div></div>
  <div class="metric"><div class="value" style="color:#e74c3c">{failed}</div><div class="label">Failed</div></div>
  <div class="metric">
    <div class="value"><span class="risk-badge">{risk:.1}</span></div>
    <div class="label">Risk Score (0–100)</div>
  </div>
</div>

<h2>Attack Results</h2>
<table>
  <thead>
    <tr>
      <th>Attack</th><th>Status</th><th>Confidence</th><th>Duration</th>
      <th>Matched Vulns</th><th>Details</th>
    </tr>
  </thead>
  <tbody>{rows}</tbody>
</table>

<h2>Recommendations</h2>
<div class="rec-list"><ol>{recs}</ol></div>

<p style="margin-top:40px;color:#8b949e;font-size:0.8em">
  Generated by <strong>hw_toolkit</strong> – Red‑Team Hardware Security Platform
</p>
</body>
</html>"#,
        target    = report.target,
        total     = report.total_attacks,
        succeeded = report.succeeded,
        failed    = report.failed,
        risk      = report.risk_score,
        risk_color = risk_color,
        rows      = rows,
        recs      = recs_html,
    )
}

/// Write the HTML report to disk.
pub fn write_html_report(report: &PentestReport, out_path: &str) -> Result<()> {
    let html = render_html_report(report);
    fs::write(out_path, html)?;
    Ok(())
}

/// Export PDF via wkhtmltopdf (must be installed on PATH).
pub fn export_pdf_report(html_path: &str, pdf_path: &str) -> Result<()> {
    let status = std::process::Command::new("wkhtmltopdf")
        .args(["--quiet", html_path, pdf_path])
        .status()
        .map_err(|e| anyhow::anyhow!("wkhtmltopdf not found: {}", e))?;
    if !status.success() {
        return Err(anyhow::anyhow!("wkhtmltopdf exited with status {}", status));
    }
    Ok(())
}

/// Write a Markdown report.
pub fn write_markdown_report(report: &PentestReport, out_path: &str) -> Result<()> {
    let mut md = format!(
        "# Red‑Team Hardware Pentest Report\n\n\
        **Target**: {target}  \n\
        **Risk Score**: {risk:.1} / 100  \n\
        **Attacks**: {total} total — {succ} succeeded — {fail} failed  \n\n\
        ## Attack Results\n\n\
        | Attack | Status | Confidence | Elapsed | Matched Vulns |\n\
        |--------|--------|------------|---------|---------------|\n",
        target = report.target,
        risk   = report.risk_score,
        total  = report.total_attacks,
        succ   = report.succeeded,
        fail   = report.failed,
    );
    for r in &report.results {
        md.push_str(&format!(
            "| {} | {} | {:.0}% | {} ms | {} |\n",
            r.attack_name,
            if r.success { "✓ SUCCESS" } else { "✗ FAIL" },
            r.confidence * 100.0,
            r.elapsed_ms,
            r.matched_vulns.join(", "),
        ));
    }
    md.push_str("\n## Recommendations\n\n");
    for rec in &report.recommendations {
        md.push_str(&format!("- {}\n", rec));
    }
    fs::write(out_path, md)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::pentest::{PentestReport, AttackResult};

    fn dummy_report() -> PentestReport {
        PentestReport {
            target: "test-mcu".into(),
            total_attacks: 1,
            succeeded: 1,
            failed: 0,
            risk_score: 85.0,
            results: vec![AttackResult {
                attack_name: "VoltageGlitch".into(),
                success: true,
                confidence: 0.85,
                details: serde_json::json!({"v_drop": 1.5}),
                elapsed_ms: 42,
                matched_vulns: vec!["HW-PHYS-001".into()],
            }],
            recommendations: vec!["Add voltage supervisor IC".into()],
        }
    }

    #[test]
    fn html_contains_target() {
        let report = dummy_report();
        let html = render_html_report(&report);
        assert!(html.contains("test-mcu"));
        assert!(html.contains("VoltageGlitch"));
    }

    #[test]
    fn json_round_trip() {
        let report = dummy_report();
        let tmp = std::env::temp_dir().join("hw_report_test.json");
        write_json_report(&report, tmp.to_str().unwrap()).unwrap();
        let loaded: PentestReport = serde_json::from_str(&fs::read_to_string(&tmp).unwrap()).unwrap();
        assert_eq!(loaded.target, report.target);
        fs::remove_file(tmp).ok();
    }
}
